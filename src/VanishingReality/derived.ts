// 显示层派生：把 schema 里的裸数值翻译成界面要用的阶段名与色调。
// 全部是纯函数，不依赖 Vue，方便单独核对阈值。

export type 阶段 = {
  名: string;
  下限: number;
  注: string;
};

/** 侵蚀度 → 堕落阶段。区间取左闭右开，100 归入最后一段。 */
export const 堕落阶段表: 阶段[] = [
  { 名: '圣辉', 下限: 0, 注: '星徽完整，直播节奏照常。' },
  { 名: '摇动', 下限: 20, 注: '变身出现延时，绝招余波开始被观众看见。' },
  { 名: '侵染', 下限: 40, 注: '圣辉余量跌破一半，触肢够得着她了。' },
  { 名: '堕转', 下限: 60, 注: '名号正在改写，她开口仍是自己的声音。' },
  { 名: '灾祸', 下限: 80, 注: '名号已换成魔娼，往后她替你收欲望。' },
];

export function 堕落阶段(侵蚀度: number): 阶段 {
  return _(堕落阶段表)
    .filter(阶段 => 侵蚀度 >= 阶段.下限)
    .last()!;
}

/** 已堕落的判定线。与堕落阶段表的最后一段保持一致。 */
export const 灾祸线 = 80;

export function 已堕落(侵蚀度: number): boolean {
  return 侵蚀度 >= 灾祸线;
}

